import sys
from pathlib import Path

BANNER = "# Generated by `just codegen` from src/pdc_api_client/openapi.json. Do not edit.\n"


def postprocess(source: str) -> str:
    return BANNER + source


def main() -> None:
    path = Path(sys.argv[1])
    path.write_text(postprocess(path.read_text()))


if __name__ == "__main__":
    main()
